// Parse the collection
const cardCounts = {};

rawCollection.split('\n').forEach(line => {
    const trimmed = line.trim();
    if (!trimmed) return;

    // Match pattern: QUANTITY CARD_NAME (SET_CODE)
    const match = trimmed.match(/^(\d+)\s+(.+?)\s+\([^)]+\)\s*$/);

    if (match) {
        const quantity = parseInt(match[1]);
        const cardName = match[2].trim();

        if (!cardCounts[cardName]) {
            cardCounts[cardName] = 0;
        }
        cardCounts[cardName] += quantity;
    }
});

// Sort by name and format for output
const sortedCards = Object.keys(cardCounts).sort().map(name => {
    const qty = cardCounts[name];
    return `${qty} ${name}`;
});

